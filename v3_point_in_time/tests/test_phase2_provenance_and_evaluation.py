class ReproducibilityTests(unittest.TestCase):
    def test_14_repeated_identical_scientific_evaluation_is_reproducible(self):
        store = ForecastVintageStore()
        store.add(make_synthetic_forecast("f-repro", DECISION_TIME, TARGET_TIME, 19.5))

        def one_run(tag):
            snapshot, guard, selections = shadow_engine.select_and_build_snapshot(
                store=store, snapshot_id=f"repro-{tag}", event_year=2020, car_or_entry_id="C",
                decision_time=DECISION_TIME, current_track_temp_c=28.0, current_ambient_temp_c=20.0,
                current_track_temp_known_at=DECISION_TIME, current_ambient_temp_known_at=DECISION_TIME,
                horizons_min=[60],
            )
            with tempfile.TemporaryDirectory() as d:
                r = shadow_engine.run_single_horizon(
                    snapshot, 60, selections[60]["vintage"], 39.7950, -86.2348,
                    random_seed=123, n_mc=2000, output_dir=Path(d),
                )
                return r.prediction.expected_delta_v, r.prediction.prediction_hash

        v1, h1 = one_run("a")
        v2, h2 = one_run("b")
        self.assertEqual(v1, v2)
        self.assertNotEqual(h1, h2)  # different snapshot_id -> different prediction_id/hash, as designed


