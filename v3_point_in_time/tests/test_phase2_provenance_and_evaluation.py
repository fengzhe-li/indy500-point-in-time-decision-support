class ForecastProvenanceConsistencyTests(unittest.TestCase):
    """Items 1 and 4: snapshot provenance == actual vintage used ==
    prediction record provenance, enforced by construction."""

    def test_snapshot_selection_and_prediction_agree(self):
        store = ForecastVintageStore()
        store.add(make_synthetic_forecast("f-consistency", DECISION_TIME, TARGET_TIME, 20.0))

        snapshot, guard, selections = shadow_engine.select_and_build_snapshot(
            store=store, snapshot_id="consistency-test", event_year=2020, car_or_entry_id="C",
            decision_time=DECISION_TIME, current_track_temp_c=28.0, current_ambient_temp_c=21.0,
            current_track_temp_known_at=DECISION_TIME, current_ambient_temp_known_at=DECISION_TIME,
            horizons_min=[60],
        )
        self.assertTrue(guard.passed)
        vintage = selections[60]["vintage"]

        # 1. snapshot provenance
        self.assertEqual(snapshot.selected_forecast_ids, (vintage.forecast_id,))

        with tempfile.TemporaryDirectory() as d:
            result = shadow_engine.run_single_horizon(
                snapshot, 60, vintage, 39.7950, -86.2348, random_seed=1, n_mc=500, output_dir=Path(d),
            )
            self.assertEqual(result.status, "OK")
            # 4. actual vintage used == prediction record provenance == snapshot provenance
            self.assertEqual(result.prediction.forecast_vintage_ids, (vintage.forecast_id,))
            self.assertEqual(result.prediction.forecast_vintage_ids, snapshot.selected_forecast_ids)


class SyntheticIsolationTests(unittest.TestCase):
    """Item 5 and 15: synthetic data cannot enter, and real scientific
    rows carry non-synthetic provenance."""

    def test_5_synthetic_fixture_label_never_appears_in_real_case_table(self):
        case_table = EVAL_DIR / "phase2_case_table.csv"
        if not case_table.exists():
            self.skipTest("phase2_case_table.csv not yet generated by run_phase2_evaluation.py")
        with open(case_table, newline="", encoding="utf-8") as f:
            text = f.read()
        self.assertNotIn(SYNTHETIC_TEST_FIXTURE_LABEL, text)

    def test_15_real_case_table_forecast_source_is_noaa_not_synthetic(self):
        case_table = EVAL_DIR / "phase2_case_table.csv"
        if not case_table.exists():
            self.skipTest("phase2_case_table.csv not yet generated by run_phase2_evaluation.py")
        with open(case_table, newline="", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        supported_rows = [r for r in rows if r["applicability_status"] == "SUPPORTED"]
        self.assertGreater(len(supported_rows), 0, "expected at least one SUPPORTED case")
        for r in supported_rows:
            self.assertEqual(r["forecast_source"], "NOAA")
            self.assertNotEqual(r["forecast_source"], SYNTHETIC_TEST_FIXTURE_LABEL)


class RealisedWeatherLeakageTests(unittest.TestCase):
    """Item 6: realised future weather must not silently substitute for
    a forecast in point-in-time inference. The store only ever contains
    what was explicitly added to it -- if only a pre-decision-time
    forecast is added, a post-decision-time realised observation cannot
    be selected because it was never in the store to begin with, and
    even if it were added, a realised observation timestamped for a
    time in the future relative to decision_time would be excluded by
    the same issue_time<=decision_time filter used for forecasts."""

    def test_a_realised_observation_added_with_a_post_decision_issue_time_is_never_selected(self):
        store = ForecastVintageStore()
        # A "realised observation" masquerading as a forecast, but honestly
        # timestamped with its OWN (post-decision) observation time as issue_time.
        store.add(make_synthetic_forecast(
            "realised-obs-not-a-forecast", issue_time=TARGET_TIME, valid_time=TARGET_TIME, ambient_temp_c=99.0,
        ))
        selection = store.select(DECISION_TIME, TARGET_TIME)
        self.assertIsNone(selection)


